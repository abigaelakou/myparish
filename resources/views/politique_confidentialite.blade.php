    <h1>Politique de confidentialité – Paroisse Smart</h1>
    <p><em>Dernière mise à jour : [à compléter]</em></p>

    <p>La présente Politique de confidentialité explique comment <strong>Paroisse Smart</strong> collecte, utilise, conserve et protège les données personnelles des utilisateurs dans le cadre de ses services (inscriptions à la catéchèse, dons, événements paroissiaux, communication avec les fidèles, documents de paroisse, archives).</p>
    <p>Nous nous engageons à respecter la confidentialité et la sécurité de vos informations personnelles.</p>

    <h2>1. Données collectées</h2>
    <ul>
        <li>Données d’identité : nom, prénom, sexe, date de naissance, situation matrimoniale.</li>
        <li>Données de contact : adresse email, numéro de téléphone.</li>
        <li>Données religieuses : sacrements reçus, inscriptions catéchétiques, participation aux activités paroissiales.</li>
        <li>Données de paiement : montant des dons, frais d’inscription ou participation financière (les informations bancaires ne sont pas stockées par nous mais par nos prestataires sécurisés).</li>
        <li>Données techniques : adresse IP, identifiants de connexion, logs de navigation, cookies (uniquement pour la version web).</li>
    </ul>

    <h2>2. Utilisation des données</h2>
    <p>Les informations collectées sont utilisées pour :</p>
    <ul>
        <li>Gérer les inscriptions aux catéchèses, événements et autres activités paroissiales.</li>
        <li>Enregistrer et suivre les dons et paiements effectués.</li>
        <li>Générer des reçus de paiement ou attestations.</li>
        <li>Communiquer avec vous (notifications, rappels, informations paroissiales).</li>
        <li>Améliorer l’expérience utilisateur et les services proposés.</li>
    </ul>
    <p><strong>Vos données ne seront jamais vendues à des tiers.</strong></p>

    <h2>3. Partage des données</h2>
    <ul>
        <li>Les paroisses partenaires pour la gestion locale des activités.</li>
        <li>Nos prestataires techniques (hébergement, emailing, paiement sécurisé).</li>
        <li>Les autorités légales, uniquement si la loi nous y oblige.</li>
    </ul>

    <h2>4. Sécurité des données</h2>
    <ul>
        <li>Connexions sécurisées (HTTPS, chiffrement SSL).</li>
        <li>Stockage protégé des données.</li>
        <li>Accès limité uniquement aux responsables autorisés.</li>
    </ul>

    <h2>5. Conservation des données</h2>
    <ul>
        <li>Données liées aux inscriptions : conservées le temps de votre participation.</li>
        <li>Données de paiement : conservées selon les durées légales comptables.</li>
        <li>Données de contact : supprimées à votre demande ou après inactivité prolongée.</li>
    </ul>

    <h2>6. Vos droits</h2>
    <ul>
        <li>Droit d’accès à vos données.</li>
        <li>Droit de rectification.</li>
        <li>Droit de suppression (sauf obligations légales).</li>
        <li>Droit d’opposition ou de retrait du consentement.</li>
        <li>Droit à la portabilité.</li>
    </ul>
    <p>📧 Contact : <strong>contact@paroissesmart.com</strong></p>

